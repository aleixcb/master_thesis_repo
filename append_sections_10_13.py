# 13a — Forecasts
new_cells.append(md(
    '### Section 13a — Expanding-Window Forecasts\n\n'
    'Same expanding-window scheme as Section 7 (GARCH baseline) for a clean comparison. '
    'At each test date $t$, EGARCH(1,1,1) is refitted on all data up to $t$, '
    'the one-step-ahead log-variance forecast is obtained, and the fixed training-sample '
    '$\\hat{\\gamma}_1, \\hat{\\gamma}_2$ are applied as an additive adjustment before '
    'exponentiating back to variance space:\n\n'
    '$$\\hat{\\sigma}^2_{t+1} = \\exp\\!\\left[\\ln(\\hat{\\sigma}^2_{t+1|t})_{\\text{EGARCH}} '
    '+ \\hat{\\gamma}_1 \\cdot \\text{Tone}_{m,t-L+1} '
    '+ \\hat{\\gamma}_2 \\cdot \\text{Vol}_{m,t-L+1}\\right] / 10^4$$\n\n'
    'The division by $10^4$ converts from percentage-return variance (EGARCH fit on returns×100) '
    'back to decimal-return variance.\n\n'
    'Budget rule: refit every step; switch to every 22 steps if any single metal exceeds '
    '15 minutes wall-clock, matching the Section 7 precedent.'
))

