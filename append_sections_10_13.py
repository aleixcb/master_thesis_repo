new_cells.append(md(
    '## Section 10 — EGARCH(1,1)-X Specification Overview\n\n'
    '### Variance equation\n\n'
    '$$\n'
    r'\ln(\sigma^2_t) = \omega + \alpha\left[|z_{t-1}| - \mathbb{E}|z_{t-1}|\right]'
    r' + \xi \cdot z_{t-1} + \beta \cdot \ln(\sigma^2_{t-1})'
    r' + \gamma_1 \cdot \text{Tone}_{m,t-1} + \gamma_2 \cdot \text{Volume}_{m,t-1}'
    '\n$$\n\n'
    r'where $z_t = \varepsilon_t / \sigma_t$ is the standardised residual and '
    r'$\mathbb{E}|z| = \sqrt{2/\pi}$ for the Normal baseline (distribution-corrected for '
    r'Student-$t$ and GED).'
    '\n\n'
    '### Why EGARCH for signed sentiment\n\n'
    'Standard GARCH constrains $\\sigma^2_t > 0$ via positivity restrictions on $\\omega, \\alpha, \\beta$, '
    'which forces any exogenous regressor entering the variance equation to be non-negative '
    '(e.g. squared or absolute sentiment). '
    'EGARCH models **log-variance** and has no positivity constraint, so standardised '
    '*signed* tone — which ranges over the real line — can enter $\\ln(\\sigma^2_t)$ directly '
    'without transformation (methodology §3.4.3). '
    'A negative coefficient $\\gamma_1 < 0$ means negative tone increases forecasted variance, '
    'the theoretically expected direction.\n\n'
    '### Empirical caveat: leverage effect\n\n'
    'EDA §5b (Engle-Ng sign bias test) found **no significant asymmetric volatility response** '
    'for any of the four metals (joint $p > 0.47$). This means the leverage parameter $\\xi$ '
    'may not be significant in-sample — the data do not require asymmetric treatment of positive '
    'vs negative *return* shocks. The EGARCH specification is retained because:\n\n'
    '1. EDA §5b tests return-sign asymmetry, not news-sentiment asymmetry — these are distinct channels.\n'
    '2. EGARCH is the natural model for signed regressors regardless of $\\xi$.\n'
    '3. $\\gamma_1$ and $\\gamma_2$ are the **primary parameters of interest**; '
    '$\\xi$ is reported for completeness but its insignificance does not invalidate the exercise.\n\n'
    '### Implementation path\n\n'
    'The `arch` library routes exogenous variables to the **mean** equation via the `x` argument; '
    'it does not expose variance-equation exogenous regressors for EGARCH through the public API. '
    'We therefore use a **two-step approach** (standard in the literature, e.g. Engle 2002):\n\n'
    '1. Fit EGARCH(1,1,1) without sentiment on the training sample — recovers $\\omega, \\alpha, \\xi, \\beta$.\n'
    '2. Regress the fitted $\\ln(\\hat{\\sigma}^2_t)$ series on the lagged sentiment regressors '
    'via OLS with Newey-West (HAC) standard errors — recovers $\\gamma_1, \\gamma_2$.\n\n'
    'For out-of-sample forecasting, the EGARCH one-step-ahead log-variance forecast is adjusted '
    'by the fixed training-sample $\\hat{\\gamma}_1, \\hat{\\gamma}_2$ before exponentiating. '
    'The EGARCH base AIC/BIC is reported for comparisons; the marginal sentiment contribution '
    'is evaluated through coefficient significance and residual diagnostics.'
))

